//! SQL 方言表。
//!
//! 之前每个驱动各自 `format!` 拼 SQL，同一件事（引号、分页、转义）在 6 处各写一遍，
//! 改一处语法要翻 6 个文件。这里用一张 Rust 表收口——6 个方言用 `match` 足够，
//! 不需要 build.rs 生成 YAML（那是 dbx 为 37 个方言准备的做法，对本项目是过度设计）。

use crate::generated::DatabaseType;

/// SQL 方言种类。非 SQL 数据源返回 `None`。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SqlDialect {
    Mysql,
    Postgres,
    Sqlite,
    Mssql,
    Clickhouse,
    Oracle,
}

#[allow(
    dead_code,
    reason = "pagination / placeholder / is_read_only_statement 供阶段 2 的 SQL 家族合并使用，先随方言表一起落地"
)]
impl SqlDialect {
    /// 由数据源类型推断方言。非 SQL 数据源（KV / 消息 / 对象存储 / 搜索）返回 `None`。
    pub const fn from_db_type(db_type: DatabaseType) -> Option<Self> {
        match db_type {
            DatabaseType::Mysql => Some(SqlDialect::Mysql),
            DatabaseType::Postgresql => Some(SqlDialect::Postgres),
            DatabaseType::Sqlite => Some(SqlDialect::Sqlite),
            DatabaseType::Mssql => Some(SqlDialect::Mssql),
            DatabaseType::Clickhouse => Some(SqlDialect::Clickhouse),
            DatabaseType::Oracledb => Some(SqlDialect::Oracle),
            _ => None,
        }
    }

    /// 标识符引号：(前缀, 后缀)。MySQL 用反引号，SQL Server 用方括号，其余双引号。
    pub const fn ident_delimiters(self) -> (char, char) {
        match self {
            SqlDialect::Mysql => ('`', '`'),
            SqlDialect::Mssql => ('[', ']'),
            SqlDialect::Postgres
            | SqlDialect::Sqlite
            | SqlDialect::Clickhouse
            | SqlDialect::Oracle => ('"', '"'),
        }
    }

    /// 给标识符加引号，并转义内部可能出现的闭合符。
    pub fn quote_ident(self, ident: &str) -> String {
        let (open, close) = self.ident_delimiters();
        let escaped = if open == close {
            ident.replace(close, &format!("{close}{close}"))
        } else {
            ident
                .replace(close, &format!("{close}{close}"))
                .replace(open, &format!("{open}{open}"))
        };
        format!("{open}{escaped}{close}")
    }

    /// 分页子句。
    ///
    /// `offset` 为 0 时省略 OFFSET，避免生成 `LIMIT n OFFSET 0` 这种在部分引擎上
    /// 走不到索引优化的写法。
    pub fn pagination(self, offset: u64, limit: u64) -> String {
        match self {
            SqlDialect::Mysql
            | SqlDialect::Postgres
            | SqlDialect::Sqlite
            | SqlDialect::Clickhouse => {
                if offset == 0 {
                    format!("LIMIT {limit}")
                } else {
                    format!("LIMIT {limit} OFFSET {offset}")
                }
            }
            SqlDialect::Mssql => {
                // SQL Server 的 OFFSET/FETCH 必须搭配 ORDER BY，调用方需自行保证。
                format!("OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY")
            }
            SqlDialect::Oracle => {
                // Oracle 12c+ 语法。
                format!("OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY")
            }
        }
    }

    /// 位置占位符风格。SQLite/MySQL 用 `?`，Postgres 用 `$n`，SQL Server 用 `@pn`。
    pub fn placeholder(self, index: usize) -> String {
        match self {
            SqlDialect::Mysql | SqlDialect::Sqlite | SqlDialect::Clickhouse => "?".to_string(),
            SqlDialect::Postgres => format!("${index}"),
            SqlDialect::Mssql => format!("@p{index}"),
            SqlDialect::Oracle => format!(":{index}"),
        }
    }

    /// `CREATE TABLE` 建表向导模板。
    ///
    /// 文案与前端旧的 `utils/SqlUtils.ts` 输出**逐字一致**：这次只是把生成逻辑
    /// 从 TypeScript 收敛到方言表，不改变用户看到的 SQL。
    pub fn create_table_template(self, table: &str) -> String {
        match self {
            SqlDialect::Mysql => format!(
                "CREATE TABLE `{table}` (\n    `id` INT NOT NULL PRIMARY KEY AUTO_INCREMENT COMMENT 'Primary Key',\n    `create_time` DATETIME COMMENT 'Create Time',\n    `name` VARCHAR(255)\n) COMMENT '';"
            ),
            SqlDialect::Sqlite => format!(
                "CREATE TABLE `{table}` (\n    `id` INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,\n    `content` TEXT\n);"
            ),
            SqlDialect::Oracle => format!(
                "CREATE TABLE \"{table}\" (\n    \"ID\" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,\n    \"CREATED_AT\" TIMESTAMP DEFAULT SYSTIMESTAMP,\n    \"NAME\" VARCHAR2(255)\n);"
            ),
            SqlDialect::Postgres => format!(
                "CREATE TABLE \"{table}\" (\n    \"id\" SERIAL PRIMARY KEY,\n    \"created_at\" TIMESTAMP DEFAULT NOW(),\n    \"name\" VARCHAR(255)\n);"
            ),
            SqlDialect::Mssql => format!(
                "CREATE TABLE [{table}] (\n    [id] INT NOT NULL IDENTITY(1,1) PRIMARY KEY,\n    [created_at] DATETIME DEFAULT GETDATE(),\n    [name] NVARCHAR(255)\n);"
            ),
            SqlDialect::Clickhouse => format!(
                "CREATE TABLE {table} (\n    id UInt32,\n    created_at DateTime DEFAULT now(),\n    name String\n) ENGINE = MergeTree()\nORDER BY id;"
            ),
        }
    }

    /// `ALTER TABLE ... ADD COLUMN` 向导模板。
    pub fn add_column_template(self, table: &str) -> String {
        match self {
            SqlDialect::Mysql => format!(
                "ALTER TABLE `{table}`\n    ADD COLUMN `new_column_name` [TYPE] COMMENT '' AFTER `existing_column`;"
            ),
            SqlDialect::Sqlite => {
                format!("\nALTER TABLE `{table}`\n    ADD COLUMN `new_column_name` [TYPE];")
            }
            SqlDialect::Oracle => {
                format!("ALTER TABLE \"{table}\"\n    ADD \"NEW_COLUMN_NAME\" [TYPE];")
            }
            SqlDialect::Postgres => {
                format!("ALTER TABLE \"{table}\"\n    ADD COLUMN \"new_column_name\" [TYPE];")
            }
            SqlDialect::Mssql => format!("ALTER TABLE [{table}]\n    ADD [new_column_name] [TYPE] NULL;"),
            SqlDialect::Clickhouse => {
                format!("ALTER TABLE {table}\n    ADD COLUMN new_column_name [TYPE];")
            }
        }
    }

    /// `CREATE INDEX` 向导模板。
    pub fn create_index_template(self, table: &str) -> String {
        match self {
            SqlDialect::Mysql => format!(
                "ALTER TABLE `{table}` ADD KEY `idx_{table}_column` (`column_name_to_index`);"
            ),
            SqlDialect::Sqlite => {
                format!("CREATE INDEX `idx_{table}_column` ON `{table}` (`column_name_to_index`);")
            }
            SqlDialect::Oracle => {
                let upper = table.to_uppercase();
                format!(
                    "CREATE INDEX \"IDX_{upper}_COL\" ON \"{upper}\" (\"COLUMN_NAME_TO_INDEX\");"
                )
            }
            SqlDialect::Postgres => format!(
                "CREATE INDEX \"idx_{table}_column\" ON \"{table}\" (\"column_name_to_index\");"
            ),
            SqlDialect::Mssql => {
                format!("CREATE INDEX [idx_{table}_column] ON [{table}] ([column_name_to_index]);")
            }
            SqlDialect::Clickhouse => format!(
                "CREATE INDEX idx_{table}_column column_name_to_index TYPE minmax GRANULARITY 1;"
            ),
        }
    }

    /// 非 SQL 数据源的建表兜底文案（保留历史上的 warning 注释，行为不变）。
    pub fn unknown_create_table_template(connection_type: i32, table: &str) -> String {
        format!(
            "/* Warning: Unknown connection type ({connection_type}), using generic CREATE TABLE for {table} */\nCREATE TABLE {table} (\n    id INT PRIMARY KEY,\n    name VARCHAR(255)\n);"
        )
    }

    /// 非 SQL 数据源的加列兜底文案。
    pub fn unknown_add_column_template(connection_type: i32, table: &str) -> String {
        format!(
            "/* Warning: Unknown connection type ({connection_type}), using generic ALTER TABLE ADD COLUMN for {table} */\nALTER TABLE {table} ADD COLUMN new_column_name [TYPE];"
        )
    }

    /// 非 SQL 数据源的建索引兜底文案。
    pub fn unknown_create_index_template(connection_type: i32, table: &str) -> String {
        format!(
            "/* Warning: Unknown connection type ({connection_type}), using generic CREATE INDEX for {table} */\nCREATE INDEX idx_{table}_column ON {table} (column_name_to_index);"
        )
    }

    /// 判断一条 SQL 是否为只读查询（用于决定是否走 `fetch_all` 而不是 `execute`）。
    pub fn is_read_only_statement(sql: &str) -> bool {
        let trimmed = sql.trim_start();
        let mut head = trimmed.split_whitespace();
        let Some(first) = head.next() else {
            return false;
        };
        matches!(
            first.to_ascii_uppercase().as_str(),
            "SELECT" | "SHOW" | "PRAGMA" | "EXPLAIN" | "DESCRIBE" | "DESC" | "WITH" | "VALUES"
        )
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
mod tests {
    use super::*;

    #[test]
    fn create_table_templates_match_legacy_output() {
        assert_eq!(
            SqlDialect::Mysql.create_table_template("new_table"),
            "CREATE TABLE `new_table` (\n    `id` INT NOT NULL PRIMARY KEY AUTO_INCREMENT COMMENT 'Primary Key',\n    `create_time` DATETIME COMMENT 'Create Time',\n    `name` VARCHAR(255)\n) COMMENT '';"
        );
        assert_eq!(
            SqlDialect::Postgres.create_table_template("t"),
            "CREATE TABLE \"t\" (\n    \"id\" SERIAL PRIMARY KEY,\n    \"created_at\" TIMESTAMP DEFAULT NOW(),\n    \"name\" VARCHAR(255)\n);"
        );
        assert_eq!(
            SqlDialect::Sqlite.add_column_template("t"),
            "\nALTER TABLE `t`\n    ADD COLUMN `new_column_name` [TYPE];"
        );
        assert_eq!(
            SqlDialect::Mysql.create_index_template("t"),
            "ALTER TABLE `t` ADD KEY `idx_t_column` (`column_name_to_index`);"
        );
    }

    #[test]
    fn unknown_dialect_keeps_legacy_warning() {
        let text = SqlDialect::unknown_create_table_template(9, "t");
        assert!(text.starts_with("/* Warning: Unknown connection type (9)"));
    }

    #[test]
    fn quotes_identifiers_per_dialect() {
        assert_eq!(SqlDialect::Mysql.quote_ident("order"), "`order`");
        assert_eq!(SqlDialect::Postgres.quote_ident("order"), "\"order\"");
        assert_eq!(SqlDialect::Mssql.quote_ident("order"), "[order]");
    }

    #[test]
    fn doubles_embedded_quotes() {
        assert_eq!(SqlDialect::Postgres.quote_ident("we\"ird"), "\"we\"\"ird\"");
        assert_eq!(SqlDialect::Mysql.quote_ident("we`ird"), "`we``ird`");
    }

    #[test]
    fn pagination_omits_zero_offset() {
        assert_eq!(SqlDialect::Mysql.pagination(0, 100), "LIMIT 100");
        assert_eq!(SqlDialect::Mysql.pagination(20, 100), "LIMIT 100 OFFSET 20");
        assert_eq!(
            SqlDialect::Mssql.pagination(20, 100),
            "OFFSET 20 ROWS FETCH NEXT 100 ROWS ONLY"
        );
    }

    #[test]
    fn placeholders_follow_dialect() {
        assert_eq!(SqlDialect::Sqlite.placeholder(1), "?");
        assert_eq!(SqlDialect::Postgres.placeholder(1), "$1");
        assert_eq!(SqlDialect::Mssql.placeholder(1), "@p1");
    }

    #[test]
    fn identifies_read_only_statements() {
        assert!(SqlDialect::is_read_only_statement("  select 1"));
        assert!(SqlDialect::is_read_only_statement(
            "WITH x AS (SELECT 1) SELECT * FROM x"
        ));
        assert!(!SqlDialect::is_read_only_statement("update t set a = 1"));
    }

    #[test]
    fn maps_db_types_to_dialects() {
        assert_eq!(
            SqlDialect::from_db_type(DatabaseType::Mysql),
            Some(SqlDialect::Mysql)
        );
        assert_eq!(SqlDialect::from_db_type(DatabaseType::Redis), None);
    }
}
